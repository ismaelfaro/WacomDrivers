#!/bin/bash
# Concatenates the README, AGENTS.md, the docs and the protocol source into llms-full.txt, so a chat
# assistant without repository access can read everything from one URL. Re-run after editing any doc.
set -euo pipefail
cd "$(dirname "$0")/.."

FILES=(
    README.md
    AGENTS.md
    docs/STATUS.md
    docs/PROTOCOL.md
    docs/ARCHITECTURE.md
    docs/MACOS-INTEGRATION.md
    docs/TROUBLESHOOTING.md
    docs/devices.json
    Sources/BambooKit/Protocol.swift
)

{
    echo "# Wacom Bamboo for macOS: full documentation"
    echo
    echo "Generated by scripts/make-llms-full.sh. Source of truth: https://github.com/ismaelfaro/WacomDrivers"
    for f in "${FILES[@]}"; do
        echo
        echo "================================================================"
        echo "FILE: $f"
        echo "================================================================"
        cat "$f"
    done
} > llms-full.txt

echo "Wrote llms-full.txt ($(wc -c < llms-full.txt | tr -d ' ') bytes)"
